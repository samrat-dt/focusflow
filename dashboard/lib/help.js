import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LABEL } from './launchd.js';

// The single source of the recovery steps. The on-screen panel and banner, the
// standalone help page, the README and setup's output are all rendered from
// helpContent(), so the wording cannot drift between them.

export const APP_NAME = 'Focusflow';
export const LAUNCHER_FILE = `${APP_NAME}.app`;
export const HELP_PAGE_FILE = `${APP_NAME} Help.html`;
export const PROJECT_PLACEHOLDER = '<project folder>';
export const README_START = '<!-- help:start (generated by `npm run docs` from lib/help.js; do not edit by hand) -->';
export const README_END = '<!-- help:end -->';

const PUBLIC_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');

// Quote for the shell only when needed, so ordinary paths stay readable.
export function shQuote(p) {
  return /^[\w@%+=:,./-]+$/.test(p) ? p : `'${p.replace(/'/g, `'\\''`)}'`;
}

const OPEN_TERMINAL = 'Open Terminal (press Command-Space, type Terminal, press Enter).';

// `projectDir` is the real folder (computed at run time by the caller). Without
// it (the README) the commands carry a placeholder instead.
export function helpContent({ projectDir = null, port = 4177, label = LABEL } = {}) {
  const dir = projectDir == null ? PROJECT_PLACEHOLDER : shQuote(projectDir);
  const address = `127.0.0.1:${port}`;
  return {
    app: APP_NAME,
    address,
    token: {
      heading: 'This window needs its access key',
      what: 'Focusflow is running, but this window does not have the private key that lets it show your work (this happens after clearing browser data, or in a new browser).',
      steps: [
        { text: OPEN_TERMINAL },
        { text: 'Copy this command, paste it into Terminal, and press Enter:', command: 'focusflow dashboard open' },
        { text: 'Focusflow opens with its key and remembers it. You will not need to do this again.' },
      ],
    },
    server: {
      heading: 'Focusflow is not running',
      what: 'The Focusflow service on this Mac is not running, so there is nothing to show yet.',
      // Used instead of `heading`/`what` when the page is open and the server goes away.
      stopped: { heading: 'Focusflow stopped answering', what: 'Its service on this Mac stopped, so this page cannot update. This message clears by itself as soon as it is back.' },
      steps: [
        { text: OPEN_TERMINAL },
        { text: 'Copy this command, paste it into Terminal, and press Enter:', command: 'focusflow dashboard start' },
        { text: `Reload this page (or open ${address}).` },
      ],
      fallback: {
        text: 'If that says the login item is not installed, run this instead and leave that Terminal window open:',
        command: `cd ${dir} && npm start`,
      },
    },
    launcher: {
      file: LAUNCHER_FILE,
      text: `Easier: open "${LAUNCHER_FILE}" (in your Applications folder). It starts Focusflow if it is not running and opens it with its key.`,
      gatekeeper: 'If macOS says it cannot verify the app, right-click it, choose Open, then choose Open again.',
    },
  };
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

// ---- plain text (setup output) -------------------------------------------------

function caseText(c, { heading = c.heading, what = c.what } = {}) {
  const out = [heading, `  ${what}`, ''];
  c.steps.forEach((s, i) => {
    out.push(`  ${i + 1}. ${s.text}`);
    if (s.command) out.push('', `      ${s.command}`, '');
  });
  if (out[out.length - 1] !== '') out.push('');
  if (c.fallback) out.push(`  ${c.fallback.text}`, '', `      ${c.fallback.command}`, '');
  return out.join('\n');
}

export function renderText(content) {
  const l = content.launcher;
  return [caseText(content.token), caseText(content.server), `${l.text}\n${l.gatekeeper}`, ''].join('\n');
}

// ---- markdown (README) ---------------------------------------------------------

function caseMarkdown(c) {
  const out = [`### ${c.heading}`, '', c.what, ''];
  c.steps.forEach((s, i) => {
    out.push(`${i + 1}. ${s.text}`);
    if (s.command) out.push('', '   ```', `   ${s.command}`, '   ```', '');
  });
  if (out[out.length - 1] !== '') out.push('');
  if (c.fallback) out.push(c.fallback.text, '', '```', c.fallback.command, '```', '');
  return out.join('\n');
}

export function renderMarkdown(content) {
  const l = content.launcher;
  return [caseMarkdown(content.token), caseMarkdown(content.server), `${l.text} ${l.gatekeeper}`].join('\n');
}

export function readmeBlock() {
  return `${README_START}\n${renderMarkdown(helpContent({}))}\n${README_END}`;
}

// ---- html ----------------------------------------------------------------------

const cmdHtml = command => `<div class="help-cmd"><code>${esc(command)}</code><button type="button" class="help-copy" data-copy="${esc(command)}">Copy</button></div>`;

// One case as an html fragment: heading, plain-words explanation, numbered steps
// with Copy buttons. The app inserts this into its panel/banner; the help page
// wraps it in a section.
export function renderCaseHtml(c, { heading = c.heading, what = c.what } = {}) {
  const steps = c.steps.map(s => `<li><span>${esc(s.text)}</span>${s.command ? cmdHtml(s.command) : ''}</li>`).join('');
  const fallback = c.fallback ? `<div class="help-fallback"><p>${esc(c.fallback.text)}</p>${cmdHtml(c.fallback.command)}</div>` : '';
  return `<h2 class="help-h">${esc(heading)}</h2><p class="help-what">${esc(what)}</p><ol class="help-steps">${steps}</ol>${fallback}`;
}

// What the running app embeds in its page: the token panel, and the banner shown
// when the server stops answering.
export function appFragments(content) {
  return {
    token: renderCaseHtml(content.token),
    lost: renderCaseHtml(content.server, content.server.stopped),
    launcher: `<p class="help-launcher">${esc(content.launcher.text)} <span class="muted">${esc(content.launcher.gatekeeper)}</span></p>`,
  };
}

